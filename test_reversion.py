class ReversionBacktestTests(unittest.TestCase):
    def test_exact_expiry_nonoverlap_missing_bars_and_summary(self):
        index = pd.date_range("2026-01-01", periods=300, freq="5min")
        df = pd.DataFrame(dict(open=np.arange(300.)+1,close=np.arange(300.)+1,
                               high=np.arange(300.)+2,low=np.arange(300.),volume=1),index=index)
        trades = backtest.simulate_reversion_pair("EUR/USD",df,settings("REV_RSI7"))
        self.assertTrue(trades)
        for trade in trades:
            self.assertEqual(trade["exit_time"]-trade["entry_time"],pd.Timedelta(minutes=45))
        for previous,current in zip(trades,trades[1:]):
            self.assertGreaterEqual(current["entry_time"],previous["exit_time"])
        self.assertIn("REV_RSI7",backtest.summarize(trades,"test"))
        self.assertEqual(backtest.simulate_reversion_pair("EUR/USD",df,settings()),[])
        self.assertEqual(backtest.simulate_reversion_pair("EUR/USD",df.iloc[:100],settings("REV_RSI7")),[])
        blocked = backtest.simulate_reversion_pair("EUR/USD",df,settings("REV_RSI7"),pair_enabled=lambda *args:False)
        self.assertEqual(blocked,[])
        first = trades[0]
        missing = df.drop(index=first["exit_time"])
        gap_trades = backtest.simulate_reversion_pair("EUR/USD",missing,settings("REV_RSI7"))
        self.assertNotIn(first["entry_time"],[t["entry_time"] for t in gap_trades])
        end = first["exit_time"]
        self.assertEqual(backtest.simulate_reversion_pair("EUR/USD",df,settings("REV_RSI7"),start=first["entry_time"],end=end),[])

    def test_minute_backtest_includes_exhaustive_reversion_events(self):
        df = fixture()[["open","high","low","close","volume"]].resample("min").ffill()
        with patch.object(database,"get_pair_strategy_status",return_value=True), patch.object(backtest,"generate_candidates") as confluence:
            trades = backtest.simulate_pair("EUR/USD",df,step_cap=1,strategies_status=settings("REV_RSI14"))
        confluence.assert_not_called()
        self.assertTrue(trades)
        self.assertEqual({t["strategy"] for t in trades},{"REV_RSI14"})
        self.assertTrue(all(t["exp"]==60 for t in trades))


