def fixture():
    return pd.read_csv(FIXTURE, index_col=0, parse_dates=True)


def settings(*enabled):
    return dict(dict.fromkeys(rev.CONFLUENCE_KEYS, False),
                **{name: name in enabled for name in rev.PRESETS})


class IndicatorAndCandidateTests(unittest.TestCase):
    def test_research_search_golden_parity_eurusd(self):
        # Golden outputs generated by research/search.py on this 800-bar EUR/USD slice.
        expected = fixture()
        actual = rev.calculate_indicators(expected[["open", "high", "low", "close", "volume"]])
        for column in ("rsi7", "rsi14", "bb_lower", "bb_upper"):
            np.testing.assert_allclose(actual[column], expected[column], atol=1e-8, rtol=1e-10)
        for strategy in rev.PRESETS:
            np.testing.assert_array_equal(actual[strategy], expected[strategy])
            self.assertTrue((actual[strategy] != 0).any())

    def test_priority_global_and_pair_toggles(self):
        frame = rev.calculate_indicators(fixture())
        frame.loc[frame.index[-1], list(rev.PRESETS)] = 1
        now = frame.index[-1] + pd.Timedelta(minutes=5)
        for enabled, expected in [(tuple(rev.PRESETS), "REV_RSI14"),
                                  (("REV_BB3", "REV_RSI7"), "REV_BB3"),
                                  (("REV_RSI7",), "REV_RSI7")]:
            calls = Mock(return_value=True)
            candidates = rev.candidates_from_indicators("EUR/USD", frame, now, settings(*enabled), calls)
            self.assertEqual(len(candidates), 1)
            cand = candidates[0]
            self.assertEqual(cand["strategy"], expected)
            self.assertEqual(cand["exp_range"], (rev.PRESETS[expected],) * 2)
            self.assertEqual(cand["tf"], "5m")
            calls.assert_called_once_with("EUR/USD", expected)
        self.assertEqual(rev.candidates_from_indicators("EUR/USD", frame, now, settings()), [])
        enabled = lambda pair, key: key == "REV_RSI7"
        self.assertEqual(rev.candidates_from_indicators("EUR/USD", frame, now, pair_enabled=enabled)[0]["strategy"], "REV_RSI7")

    def test_closed_fresh_empty_warmup_and_bad_data(self):
        data = fixture()[["open", "high", "low", "close", "volume"]]
        expected = rev.calculate_indicators(data)
        i = np.flatnonzero(expected.REV_RSI14.to_numpy())[0]
        closed = data.iloc[:i+1]
        now = closed.index[-1] + pd.Timedelta(minutes=5)
        future = data.iloc[i+1:i+2].copy()
        future[["open", "high", "low", "close"]] = 1000.
        frames = {"5m": pd.concat([closed, future])}
        candidate = rev.generate_candidates("EUR/USD", frames, now)[0]
        self.assertEqual(candidate["current_price"], closed.close.iloc[-1])
        self.assertEqual(candidate["bar_end"], now)
        self.assertTrue(rev.generate_candidates("EUR/USD", frames, now + pd.Timedelta(seconds=180)))
        self.assertEqual(rev.generate_candidates("EUR/USD", frames, now + pd.Timedelta(seconds=181)), [])
        self.assertEqual(rev.generate_candidates("EUR/USD", {}, now), [])
        self.assertEqual(rev.generate_candidates("EUR/USD", {"5m": data.iloc[:200]}, now), [])
        with self.assertRaises(KeyError):
            rev.generate_candidates("EUR/USD", {"5m": closed.drop(columns="close")}, now)
        aware = closed.copy()
        aware.index = aware.index.tz_localize("UTC")
        self.assertEqual(rev.generate_candidates("EUR/USD", {"5m": aware}, now.tz_localize("UTC"))[0], candidate)


class GuardAndSettingsTests(unittest.TestCase):
    def test_memory_expiry_and_persisted_open_after_restart(self):
        guard = rev.ReversionGuard()
        pending = Mock(return_value=False)
        with patch.object(rev.time, "time", return_value=1000):
            with guard.reserve("EUR/USD", "REV_RSI14", "TEST", pending) as result:
                self.assertTrue(result[0])
                guard.register("EUR/USD", "REV_RSI14", 60)
            with guard.reserve("EUR/USD", "REV_RSI14", "TEST", pending) as result:
                self.assertFalse(result[0])
            with guard.reserve("EUR/USD", "REV_RSI7", "TEST", pending) as result:
                self.assertTrue(result[0])
        with patch.object(rev.time, "time", return_value=4600):
            with guard.reserve("EUR/USD", "REV_RSI14", "TEST", pending) as result:
                self.assertTrue(result[0])
        pending.return_value = True
        with rev.ReversionGuard().reserve("EUR/USD", "REV_RSI14", "TEST", pending) as result:
            self.assertFalse(result[0])
        pending.side_effect = RuntimeError("database unavailable")
        with rev.ReversionGuard().reserve("EUR/USD", "REV_RSI14", "TEST", pending) as result:
            self.assertFalse(result[0])

    def test_db_checks_pending_and_processing(self):
        connection = MagicMock()
        cursor = connection.cursor.return_value.__enter__.return_value
        cursor.fetchone.return_value = (True,)
        with patch.object(database, "get_connection", return_value=connection):
            self.assertTrue(database.has_open_reversion_signal("TEST", "REV_RSI14"))
            sql, parameters = cursor.execute.call_args.args
            self.assertIn("'PENDING', 'PROCESSING'", sql)
            self.assertEqual(parameters, ("TEST", "REV_RSI14"))
            cursor.execute.side_effect = RuntimeError("database unavailable")
            with self.assertRaises(RuntimeError):
                database.has_open_reversion_signal("TEST", "REV_RSI14")
        self.assertEqual(connection.close.call_count, 2)

    def test_defaults_saved_values_legacy_and_toggle_callbacks(self):
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "strategies.json"
            new = rev.load_strategy_config(path)
            self.assertEqual(new, settings(*rev.PRESETS))
            saved = dict(trend_multi=True, flat_corridor=False, market_levels=False, oscillators=True)
            path.write_text(json.dumps(saved))
            before = path.read_bytes()
            existing = rev.load_strategy_config(path)
            self.assertTrue(existing["trend_multi"])
            self.assertFalse(existing["flat_corridor"])
            self.assertFalse(existing["price_action"])
            self.assertTrue(existing["oscillators"])
            self.assertEqual(path.read_bytes(), before)
            self.assertTrue(all(existing[name] for name in rev.PRESETS))
        ns = test_batch1.bot_functions()
        db = Mock()
        db.get_pair_strategy_status.return_value = True
        ns.update(strategies_status=new, ADMIN_IDS=set(), database=db,
                  save_strategies_config=Mock(), send_strategies_menu=Mock(),
                  GROUPED_STRATEGIES={name:name for name in new})
        for preset in rev.PRESETS:
            query = Mock(data="toggle_group_" + preset)
            query.message.chat_id = 7
            ns["handle_callback"](SimpleNamespace(callback_query=query), None)
            self.assertFalse(new[preset])
            query.data = "toggle_cpair_EUR/USD_" + preset
            ns["handle_callback"](SimpleNamespace(callback_query=query), None)
            db.set_pair_strategy_status.assert_called_with("EUR/USD", preset, False)


